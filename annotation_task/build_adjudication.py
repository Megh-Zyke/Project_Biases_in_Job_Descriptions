"""Build the Potato adjudication server's inputs from each annotator's export.

    python build_adjudication.py                       # SOURCES below -> annotation_output_adjudication/
    python build_adjudication.py --source shrujaya=annotation_output_300/shrujaya/user_state.json

Potato's /adjudicate queue reads annotation_output/<user>/user_state.json, never
the CSV exports. Everyone annotated on their own server, so only the CSVs are
shared; this rebuilds a user_state.json per annotator from them (labels and
spans; the CSV carries no timing data) and writes config_adjudication.yaml,
which is config.yaml pointed at the new output directory with adjudication on.

A source ending in .json is a live user_state.json and is preferred when you
have it: an export is a snapshot from the last timer tick, so it can miss the
final answer given before the server stopped.

Never touches annotation_output_adjudication/adjudication/ (the decisions).
"""
import argparse
import csv
import json
import os

import yaml

TASK = os.path.abspath(os.path.dirname(__file__))
CONFIG = os.path.join(TASK, "config.yaml")
ADJ_CONFIG = os.path.join(TASK, "config_adjudication.yaml")
OUT = "annotation_output_adjudication/"
ADJUDICATOR = "shrujaya_adj"

# annotator -> live user_state.json where it is committed, else their export.
# Rows for other users in a CSV are ignored: Sruthi's also holds a stale copy of
# meghss's first 10 items and a test login "Sruths".
SOURCES = {
    "meghss": "annotation_output_300/meghss/user_state.json",
    "sruths@umich.edu": "annotation_output_300/exports/csv/Sruthi_annotations.csv",
    "shrujaya": "annotation_output_300/shrujaya/user_state.json",
}


def from_csv(path, user, schemes):
    """{instance: [[{schema, name}, value]]} and the same for spans, for one user."""
    labels, spans = {}, {}
    with open(path, newline="") as f:
        for row in csv.DictReader(f):
            if row["user_id"] != user:
                continue
            iid = row["instance_id"]
            labels[iid], spans[iid] = [], []
            for col, value in row.items():
                if col in ("instance_id", "user_id") or value == "":
                    continue
                schema, name = col.split(".", 1)
                if schema not in schemes:
                    raise SystemExit(f"{path}: column {col!r} names no scheme in config.yaml")
                if name == "_spans":
                    # the export adds an empty "text"; user_state never stores it
                    spans[iid] += [[{k: v for k, v in s.items() if k != "text"}, 1]
                                   for s in json.loads(value)]
                else:
                    labels[iid].append([{"schema": schema, "name": name}, value])
    return labels, spans


def from_state(path):
    with open(path) as f:
        state = json.load(f)
    return state["instance_id_to_label_to_value"], state["instance_id_to_span_to_value"]


def user_state(user, labels, spans, item_order):
    order = [i for i in item_order if i in labels]
    return {
        "user_id": user,
        "instance_id_ordering": order,
        "current_instance_index": len(order) - 1,
        "current_phase_and_page": ["annotation", None],
        "completed_phase_and_pages": [],
        "max_assignments": -1,
        "instance_id_to_behavioral_data": {},
        "instance_id_to_label_to_value": {i: labels[i] for i in order},
        "instance_id_to_span_to_value": {i: spans.get(i, []) for i in order},
        "phase_to_page_to_label_to_value": {},
        "phase_to_page_to_span_to_value": {},
    }


def write_config(config):
    config["output_annotation_dir"] = OUT
    config["adjudication"] = {
        "enabled": True,
        "adjudicator_users": [ADJUDICATOR],  # kept out of the comparison, so not an annotator
        "min_annotations": 2,
    }
    config["export_annotation_format"] = ["csv", "adjudication"]
    with open(ADJ_CONFIG, "w") as f:
        f.write("# Generated by build_adjudication.py from config.yaml. Edit that, then rerun.\n")
        yaml.safe_dump(config, f, sort_keys=False, allow_unicode=True, width=120)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--source", action="append", default=[], metavar="USER=PATH",
                   help="add or replace an annotator's export (.csv) or user_state.json")
    args = p.parse_args()

    sources = dict(SOURCES)
    for s in args.source:
        user, path = s.split("=", 1)
        sources[user] = path

    with open(CONFIG) as f:
        config = yaml.safe_load(f)
    schemes = {s["name"] for s in config["annotation_schemes"]}
    with open(os.path.join(TASK, config["data_files"][0])) as f:
        item_order = [json.loads(line)[config["item_properties"]["id_key"]] for line in f]

    for user, path in sources.items():
        path = os.path.join(TASK, path)
        labels, spans = from_state(path) if path.endswith(".json") else from_csv(path, user, schemes)
        if not labels:
            raise SystemExit(f"{path}: no rows for user {user!r}")
        out_dir = os.path.join(TASK, OUT, user)
        os.makedirs(out_dir, exist_ok=True)
        with open(os.path.join(out_dir, "user_state.json"), "w") as f:
            json.dump(user_state(user, labels, spans, item_order), f)
        print(f"{user}: {len(labels)} items, {sum(map(len, spans.values()))} spans  <- {os.path.relpath(path, TASK)}")

    write_config(config)
    print(f"wrote {os.path.relpath(ADJ_CONFIG, TASK)}; adjudicator login: {ADJUDICATOR}")


if __name__ == "__main__":
    main()
